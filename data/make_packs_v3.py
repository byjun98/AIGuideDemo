def check(pack):
    def rank(sy):
        u = sy["unlock"]
        return {"always": 0}.get(u["type"], None) if u["type"] == "always" else (1 if u["type"] == "missions_cleared" and u["value"] == 1 else 2 if u["type"] == "enhance_count" else 3)
    rk = {s["id"]: rank(s) for s in pack["systems"]}
    bad = []
    for sy in pack["systems"]:
        for mk in sy.get("leak_markers", []):
            for c in pack["cards"]:
                if c["system"] == sy["id"] or rk[c["system"]] > rk[sy["id"]]:
                    continue
                texts = [c["text"]] + (c.get("qa", {}).get("answers") or [])
                if any(mk in t for t in texts):
                    bad.append((sy["id"], mk, c["id"]))
    return bad


